CREATE TABLE IF NOT EXISTS customers (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(160) NOT NULL,
  email VARCHAR(254) NULL UNIQUE,
  phone VARCHAR(30) NULL,
  company VARCHAR(160) NULL,
  type ENUM('Individual', 'Corporate') NOT NULL,
  status ENUM('Active', 'VIP', 'Recurring', 'Suspended') NOT NULL,
  nationality VARCHAR(100) NULL,
  assigned_user_id CHAR(36) NULL,
  notes TEXT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_by CHAR(36) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  archived_at DATETIME(6) NULL,
  INDEX idx_customers_status (archived_at, status, id),
  FOREIGN KEY (assigned_user_id) REFERENCES users(id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS leads (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(160) NOT NULL,
  email VARCHAR(254) NULL,
  phone VARCHAR(30) NULL,
  company VARCHAR(160) NULL,
  source ENUM('Website', 'Social Media', 'Referral', 'Email', 'Walk-in', 'Cold Call') NOT NULL,
  type ENUM('B2B', 'B2C') NOT NULL,
  priority ENUM('High', 'Medium', 'Low') NOT NULL,
  status ENUM('New', 'Contacted', 'Qualified', 'Proposal', 'Negotiation', 'Closed Won', 'Closed Lost') NOT NULL,
  value_amount DECIMAL(15,2) NULL,
  currency CHAR(3) NULL,
  assigned_user_id CHAR(36) NULL,
  next_follow_up_at DATETIME(6) NULL,
  notes TEXT NULL,
  converted_customer_id BIGINT UNSIGNED NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_by CHAR(36) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  archived_at DATETIME(6) NULL,
  INDEX idx_leads_status (archived_at, status, id),
  INDEX idx_leads_follow_up (next_follow_up_at),
  FOREIGN KEY (assigned_user_id) REFERENCES users(id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  FOREIGN KEY (converted_customer_id) REFERENCES customers(id),
  CHECK (value_amount IS NULL OR value_amount >= 0),
  CHECK ((value_amount IS NULL AND currency IS NULL) OR (value_amount IS NOT NULL AND currency IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS suppliers (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  full_name VARCHAR(160) NOT NULL,
  email VARCHAR(254) NULL,
  phone VARCHAR(30) NULL,
  company VARCHAR(160) NULL,
  category VARCHAR(100) NOT NULL,
  contact_name VARCHAR(160) NULL,
  country VARCHAR(100) NULL,
  city VARCHAR(100) NULL,
  status ENUM('Active', 'Inactive') NOT NULL,
  notes TEXT NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_by CHAR(36) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  archived_at DATETIME(6) NULL,
  INDEX idx_suppliers_status (archived_at, status, id),
  FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

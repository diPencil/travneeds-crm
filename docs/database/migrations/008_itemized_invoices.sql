CREATE TABLE IF NOT EXISTS finance_invoice_items (
  invoice_id BIGINT UNSIGNED NOT NULL,
  position SMALLINT UNSIGNED NOT NULL,
  description VARCHAR(1000) NOT NULL,
  quantity DECIMAL(9,3) NOT NULL,
  unit_price DECIMAL(12,2) NOT NULL,
  amount DECIMAL(18,2) NOT NULL,
  PRIMARY KEY (invoice_id, position),
  FOREIGN KEY (invoice_id) REFERENCES finance_invoices(id),
  CHECK (quantity > 0 AND unit_price >= 0 AND amount >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_invoice_counters (
  period SMALLINT UNSIGNED PRIMARY KEY,
  last_number INT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

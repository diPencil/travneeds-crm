export function useFinanceCopy() {
  const locale = useLocale();
  return {
    ...locale,
    copy: locale.isRTL ? ar : en,
    label: (value: string) => enums[value]?.[locale.isRTL ? 1 : 0] || value,
    intlLocale: locale.isRTL ? 'ar-EG' : 'en-US',
  };
}
